// Comparison operators
var x=2,y='4';
console.log("Comparison operators");
console.log("x==y: ",x==y); //Loose equality
console.log("x===y: ",x===y); //Strict equality
console.log("x!=y: ",x!=y); //Loose equality
console.log("x!==y: ",x!==y); //Strict equality
console.log("x>3: ",x>3); 
console.log("x<y: ",x<y); 
console.log("x>=y: ",x>=y); 
console.log("x<=y: ",x<=y); 